package com.example.game.model

data class ResourceCost(
  val wood: Int = 0,
  val food: Int = 0,
  val gold: Int = 0,
  val stone: Int = 0,
) {
  fun summary(): String {
    val parts = mutableListOf<String>()
    if (wood > 0) parts += "${wood}W"
    if (food > 0) parts += "${food}F"
    if (gold > 0) parts += "${gold}G"
    if (stone > 0) parts += "${stone}S"
    return parts.joinToString(" ")
  }
}

data class BuildingDef(
  val type: BuildingType,
  val category: BuildCategory,
  val cost: ResourceCost,
  val requiredAge: Age,
  val footprintTiles: Int,
  val maxHp: Int,
  val buildTimeSec: Float,
  val popBonus: Int = 0,
  val lineOfSight: Float = 6f,
  val attackDamage: Int = 0,
  val attackRange: Float = 0f,
  val attackCooldown: Float = 2.0f,
  val isDropOffWood: Boolean = false,
  val isDropOffFood: Boolean = false,
  val isDropOffGold: Boolean = false,
  val isDropOffStone: Boolean = false,
  val isWalkable: Boolean = false,
  val description: String,
)

data class UnitDef(
  val type: UnitType,
  val cost: ResourceCost,
  val requiredAge: Age,
  val trainedAt: BuildingType,
  val trainTimeSec: Float,
  val maxHp: Int,
  val attack: Int,
  val meleeArmor: Int,
  val pierceArmor: Int,
  val range: Float,
  val speed: Float,
  val attackCooldown: Float,
  val lineOfSight: Float,
  val isRanged: Boolean = false,
  val isCavalry: Boolean = false,
  val isInfantry: Boolean = false,
  val isSiege: Boolean = false,
  val isArmored: Boolean = false,
  val isFlying: Boolean = false,
  val bonusVsCavalry: Int = 0,
  val bonusVsArchers: Int = 0,
  val bonusVsBuildings: Int = 0,
  val bonusVsArmored: Int = 0,
  val requiredTech: TechType? = null,
)

data class TechDef(
  val type: TechType,
  val cost: ResourceCost,
  val requiredAge: Age,
  val researchedAt: BuildingType,
  val researchTimeSec: Float,
  val requiredBuildings: Set<BuildingType> = emptySet(),
  val requiredTechs: Set<TechType> = emptySet(),
)

data class TechRequirementStatus(
  val missingAge: Age? = null,
  val missingBuildings: List<BuildingType> = emptyList(),
  val missingTechs: List<TechType> = emptyList(),
) {
  val isMet: Boolean
    get() = missingAge == null && missingBuildings.isEmpty() && missingTechs.isEmpty()
}

