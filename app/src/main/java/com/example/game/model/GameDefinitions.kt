  fun missingTechRequirements(world: GameWorld, faction: Faction, techType: TechType): TechRequirementStatus {
    val fState = world.stateFor(faction)
    val def = techDefs.getValue(techType)
    val missingAge = if (fState.age.index < def.requiredAge.index) def.requiredAge else null
    val completedTypes = world.buildings.filter { it.faction == faction && it.isComplete }.map { it.type }.toSet()
    val missingBuildings = def.requiredBuildings.filter { it !in completedTypes }
    val missingTechs = def.requiredTechs.filter { it !in fState.researchedTechs }
    return TechRequirementStatus(
      missingAge = missingAge,
      missingBuildings = missingBuildings,
      missingTechs = missingTechs,
    )
  }

  fun areTechPrerequisitesMet(world: GameWorld, faction: Faction, techType: TechType): Boolean =
    missingTechRequirements(world, faction, techType).isMet

  fun adjustedBuildingCost(type: BuildingType, civ: Civilization): ResourceCost {
    val base = buildingDefs.getValue(type).cost
    return if (civ == Civilization.FRANKS && type == BuildingType.FARM) {
      base.copy(wood = (base.wood * 0.75f).toInt())
    } else base
  }

  fun adjustedUnitCost(type: UnitType, civ: Civilization): ResourceCost {
    val base = unitDefs.getValue(type).cost
    return if (civ == Civilization.BYZANTINES && (type == UnitType.SPEARMAN || type == UnitType.PIKEMAN || type == UnitType.SKIRMISHER)) {
      base.copy(wood = (base.wood * 0.8f).toInt(), food = (base.food * 0.8f).toInt())
    } else base
  }

  fun effectiveBuildingMaxHp(type: BuildingType, civ: Civilization): Int {
    val base = buildingDefs.getValue(type).maxHp
    return when {
      civ == Civilization.BYZANTINES -> (base * 1.20f).toInt()
      civ == Civilization.TEUTONS && (type == BuildingType.WATCH_TOWER || type == BuildingType.CASTLE) ->
        (base * 1.25f).toInt()
      else -> base
    }
  }

  fun effectiveBuildingMaxHp(type: BuildingType, state: FactionState): Int {
    var hp = effectiveBuildingMaxHp(type, state.civilization).toFloat()
    if (TechType.STONE_SHAFT_MINING in state.researchedTechs) hp *= 1.10f
    if (TechType.MASONRY in state.researchedTechs) hp *= 1.15f
    if (TechType.ARCHITECTURE in state.researchedTechs) hp *= 1.20f
    return hp.toInt()
  }
